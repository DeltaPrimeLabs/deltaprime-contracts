function generate(chain) {
  const c = CONFIGS[chain];
  return (
    '// SPDX-License-Identifier: BUSL-1.1\n' +
    '// AUTO-GENERATED by tools/scripts/select-chain-config.js — DO NOT EDIT BY HAND.\n' +
    `// Active chain: ${chain}\n` +
    'pragma solidity 0.8.17;\n' +
    '\n' +
    '/**\n' +
    ' * DeploymentChainConfig\n' +
    ' * The single source of chain-specific constants consumed by DeploymentConstants.\n' +
    ' * Regenerate with: node tools/scripts/select-chain-config.js <test|avalanche|arbitrum>\n' +
    ' * Default checked-in state is "test" (local Forge fixtures deployCodeTo() at these\n' +
    ' * addresses). CI verifies this file matches its generator (--check mode).\n' +
    ' **/\n' +
    'library DeploymentChainConfig {\n' +
    `    string internal constant CHAIN_KEY = "${chain}";\n` +
    '\n' +
    `    bytes32 internal constant NATIVE_TOKEN_SYMBOL = ${c.NATIVE_TOKEN_SYMBOL};\n` +
    `    address internal constant NATIVE_ADDRESS = ${c.NATIVE_ADDRESS};\n` +
    `    address internal constant DIAMOND_BEACON = ${c.DIAMOND_BEACON};\n` +
    `    address internal constant SMART_LOANS_FACTORY = ${c.SMART_LOANS_FACTORY};\n` +
    `    address internal constant TOKEN_MANAGER = ${c.TOKEN_MANAGER};\n` +
    `    address internal constant ADDRESS_PROVIDER = ${c.ADDRESS_PROVIDER};\n` +
    `    address internal constant FEES_TREASURY = ${c.FEES_TREASURY};\n` +
    `    address internal constant STABILITY_POOL = ${c.STABILITY_POOL};\n` +
    `    address internal constant GMX_DATA_STORE = ${c.GMX_DATA_STORE};\n` +
    `    address internal constant GMX_READER = ${c.GMX_READER};\n` +
    `    address internal constant GLV_READER = ${c.GLV_READER};\n` +
    `    address internal constant DEPOSIT_SWAP = ${c.DEPOSIT_SWAP};\n` +
    '}\n'
  );
}

const arg = process.argv[2];

if (arg === '--check') {
  if (!fs.existsSync(OUTPUT)) {
    console.error(`ERROR: ${OUTPUT} does not exist`);
    process.exit(1);
  }
  const ondisk = fs.readFileSync(OUTPUT, 'utf8');
  const match = ondisk.match(/^\/\/ Active chain: (\S+)$/m);
  if (!match) {
    console.error('ERROR: cannot find "// Active chain: <key>" in existing file');
    process.exit(1);
  }
  const chain = match[1];
  if (!CONFIGS[chain]) {
    console.error(`ERROR: unknown chain key "${chain}" extracted from file`);
    process.exit(1);
  }
  const expected = generate(chain);
  if (ondisk === expected) {
    console.log(`OK: ${OUTPUT} matches generator output for chain="${chain}"`);
    process.exit(0);
  } else {
    // Produce a simple line-level diff for the error message
    const aLines = ondisk.split('\n');
    const bLines = expected.split('\n');
    const maxLen = Math.max(aLines.length, bLines.length);
    const diffs = [];
    for (let i = 0; i < maxLen; i++) {
      if (aLines[i] !== bLines[i]) {
        diffs.push(`  line ${i + 1}: on-disk=${JSON.stringify(aLines[i])} expected=${JSON.stringify(bLines[i])}`);
      }
    }
    console.error(`ERROR: ${OUTPUT} does not match generator output for chain="${chain}".\nDiffering lines:\n${diffs.join('\n')}`);
    process.exit(1);
  }
}

if (!arg || !CONFIGS[arg]) {
  console.error('Usage: node tools/scripts/select-chain-config.js <test|avalanche|arbitrum>');
  console.error('       node tools/scripts/select-chain-config.js --check');
  process.exit(2);
}

const content = generate(arg);
fs.writeFileSync(OUTPUT, content, 'utf8');
console.log(`Wrote ${OUTPUT} (chain=${arg})`);
